// نسخة الحساب في المتصفح: كل تحديث للصفحة يأتي بلقطة جديدة منه من الخادم، فتحل محل النسخة المحلية، إلا
// إن كانت أقدم منها. تحديثٌ طُلب قبل كتابة في الحساب (مثل «اجعله نموذجي المفضل») قد يصل بعدها، فيمحو التغيير
// من الشاشة مع أنه محفوظ. كل نسخة تحمل وقت قراءتها على الخادم (readAt)، فتُقارن أوقات الخادم بعضها ببعض.

/** النسخة القادمة دائمًا، إلا إن كانت للحساب نفسه وقُرئت قبل النسخة الحالية. الخروج وتبديل الحساب لا ينتظران. */
export function newerUser<U extends { id: string; readAt: number }>(cur: U | null, next: U | null): U | null {
  return cur && next && next.id === cur.id && next.readAt < cur.readAt ? cur : next;
}
