import { localizeModel, modelById } from "@/lib/catalog/models";
import { all, get, type ConsultRow, type MessageRow } from "@/lib/db";
import { authed, fail } from "@/lib/http";
import { langOf, makeT } from "@/lib/i18n";

export const GET = authed<{ params: Promise<{ id: string }> }>(async (req, user, ctx) => {
  const lang = langOf(req);
  const t = makeT(lang);
  const c = await get<ConsultRow>("SELECT * FROM consultations WHERE id = ? AND user_id = ?", (await ctx.params).id, user.id);
  if (!c) return fail(404, t("الاستشارة غير موجودة.", "Consultation not found."));
  const msgs = await all<MessageRow>("SELECT * FROM messages WHERE consultation_id = ? ORDER BY created_at, id", c.id);
  const name = (id: string | null) => { const d = modelById(id); return d ? localizeModel(d, lang).name : t("المساعد", "Assistant"); };
  const md = [
    `# ${c.title}`,
    `${t("تاريخ الإنشاء:", "Created:")} ${new Date(c.created_at).toISOString()}`,
    "",
    ...msgs.map((m) =>
      m.role === "user"
        ? `## ${t("المستخدم", "User")}\n\n${m.content}\n`
        : `## ${name(m.model_id)}${m.engine === "demo" ? t(" (محرك تجريبي)", " (demo engine)") : t(" (مولَّد بالذكاء الاصطناعي)", " (generated by AI)")}\n\n${m.content}\n`,
    ),
  ].join("\n");
  return new Response(md, {
    headers: {
      "content-type": "text/markdown; charset=utf-8",
      "content-disposition": `attachment; filename="hessara-${c.id}.md"`,
    },
  });
});
