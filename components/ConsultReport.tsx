// تقرير الاستشارة: السؤال والإجابات بأسماء نماذجها، والمراجعات النقدية بأحكامها وملاحظاتها وحدودها.
// مكوّن خادم يعرضه تقرير صاحب الاستشارة ورابط المشاركة للقراءة فقط، ومصمَّم للطباعة أيضًا.
import { fmtDate } from "./bits";
import { Markdown } from "./Markdown";
import { agentById } from "@/lib/catalog/agents";
import { localizeModel, modelById } from "@/lib/catalog/models";
import { makeT, type Lang } from "@/lib/i18n";
import type { ReportData } from "@/lib/report";
import { modeById, type ReviewResult } from "@/lib/review/types";

const VER = { pass: { ar: "مستوفى", en: "Met" }, fail: { ar: "غير مستوفى", en: "Not met" }, unclear: { ar: "غير محسوم", en: "Undecided" } } as const;
const SEV = { high: { ar: "أهمية عالية", en: "High importance" }, medium: { ar: "أهمية متوسطة", en: "Medium importance" }, low: { ar: "أهمية منخفضة", en: "Low importance" } } as const;

export function ConsultReport({ data, lang }: { data: ReportData; lang: Lang }) {
  const t = makeT(lang);
  const { c, messages, reviews } = data;
  const modelName = (id: string | null) => { const d = modelById(id); return d ? localizeModel(d, lang).name : t("نموذج غير معروف", "Unknown model"); };
  const answers = messages.filter((m) => m.role === "assistant");
  const usedModels = [...new Set(answers.map((m) => modelName(m.model_id)))];
  const agent = agentById(c.agent_id, lang);
  const answerNo = new Map(answers.map((m, i) => [m.id, i + 1]));
  const parsed = reviews.flatMap((r) => {
    try { return [{ r, res: JSON.parse(r.result) as ReviewResult }]; } catch { return []; }
  });

  return (
    <article className="report">
      <header className="report__head">
        <p className="eyebrow">{t("تقرير استشارة من هسّارة", "A HESSARA consultation report")}</p>
        <h2 className="report__title">{c.title}</h2>
        <dl className="report__meta">
          <div><dt>{t("التاريخ:", "Date:")}</dt><dd>{fmtDate(c.created_at, lang)}</dd></div>
          {usedModels.length > 0 && <div><dt>{t("النماذج:", "Models:")}</dt><dd><bdi>{usedModels.join(lang === "ar" ? "، " : ", ")}</bdi></dd></div>}
          {agent && <div><dt>{t("الوكيل:", "Agent:")}</dt><dd>{agent.name}</dd></div>}
          <div><dt>{t("الإجابات:", "Answers:")}</dt><dd>{answers.length}</dd></div>
          <div><dt>{t("المراجعات:", "Reviews:")}</dt><dd>{parsed.length}</dd></div>
        </dl>
      </header>

      <section className="report__thread" aria-label={t("المحادثة", "Conversation")}>
        {messages.map((m) =>
          m.role === "user" ? (
            <div key={m.id} className="report__q">
              <h3 className="report__who">{t("السؤال", "Question")}</h3>
              <p dir="auto" className="report__text">{m.content}</p>
            </div>
          ) : (
            <div key={m.id} className="report__a">
              <h3 className="report__who">
                <span>{t(`الإجابة ${answerNo.get(m.id)}:`, `Answer ${answerNo.get(m.id)}:`)} <bdi>{modelName(m.model_id)}</bdi></span>
                <span className={`badge ${m.engine === "demo" ? "badge-warn" : ""}`}>{m.engine === "demo" ? t("قالب تجريبي — ليس ذكاءً اصطناعيًا", "Demo template — not AI") : t("مولَّد بالذكاء الاصطناعي", "Generated by AI")}</span>
                {m.status === "stopped" && <span className="badge badge-warn">{t("إجابة غير مكتملة", "Incomplete answer")}</span>}
              </h3>
              <Markdown text={m.content} />
            </div>
          ),
        )}
      </section>

      {parsed.length > 0 && (
        <section className="report__reviews" aria-label={t("المراجعات النقدية", "Critical reviews")}>
          <h3 className="t-h4">{t("المراجعات النقدية", "Critical reviews")}</h3>
          {parsed.map(({ r, res }) => (
            <div key={r.id} className="report__review">
              <h4 className="t-small">
                {modeById(r.mode, lang)?.name ?? r.mode}
                {r.message_id && answerNo.get(r.message_id) ? t(` — للإجابة ${answerNo.get(r.message_id)}`, ` — of answer ${answerNo.get(r.message_id)}`) : ""}
              </h4>
              <p className="t-small"><strong>{res.engineLabel}</strong>. {res.summary}</p>
              {res.verdicts.length > 0 && (
                <ul className="t-small">
                  {res.verdicts.map((v, i) => <li key={i}><strong>{VER[v.status][lang]}</strong>: {v.criterion}. {v.reason}</li>)}
                </ul>
              )}
              {res.findings.length > 0 && (
                <ul className="t-small">
                  {res.findings.map((f, i) => (
                    <li key={i}><strong>{f.title}</strong> ({SEV[f.severity][lang]}): {f.detail}{f.suggestion ? ` ${t("المقترح:", "Suggestion:")} ${f.suggestion}` : ""}</li>
                  ))}
                </ul>
              )}
              {res.limits.length > 0 && <p className="t-caption">{t("حدود المراجعة:", "Limits of this review:")} {res.limits.join(" ")}</p>}
            </div>
          ))}
        </section>
      )}

      <footer className="report__foot">
        <p>{t("بعض الإجابات مولّدة بالذكاء الاصطناعي وقد تحتوي أخطاء؛ تحقق منها قبل الاعتماد عليها. أسماء النماذج ملك لأصحابها.", "Some answers are generated by AI and may contain errors; check them before relying on them. Model names belong to their owners.")}</p>
        <p>{t("أُعدّ من منصة هسّارة للاستشارات بالذكاء الاصطناعي، مشروع تخرج في تخصص الذكاء الاصطناعي.", "Prepared on HESSARA, an AI consultation platform and a graduation project in artificial intelligence.")}</p>
      </footer>
    </article>
  );
}
